class Command(BaseCommand):
    help = "Создаёт курс 'AI для создания фото: ComfyUI' с текстовыми уроками"

    def handle(self, *args, **options):
        author, _ = User.objects.get_or_create(
            username="demo_author",
            defaults={"email": "author@example.com", "role": User.Role.AUTHOR, "is_staff": True},
        )
        if not author.has_usable_password():
            author.set_password("author12345")
            author.save()

        direction, _ = Direction.objects.get_or_create(
            name=COURSE["direction"],
            defaults={"slug": COURSE["direction"].lower().replace(" ", "-")},
        )
        course, created = Course.objects.update_or_create(
            slug=COURSE["slug"],
            defaults={
                "title": COURSE["title"],
                "description": COURSE["description"],
                "direction": direction,
                "level": COURSE["level"],
                "author": author,
                "is_published": True,
            },
        )
        for module_order, module_data in enumerate(COURSE["modules"], start=1):
            module, _ = Module.objects.update_or_create(
                course=course,
                order=module_order,
                defaults={"title": module_data["title"]},
            )
            for lesson_order, lesson_data in enumerate(module_data["lessons"], start=1):
                lesson, _ = Lesson.objects.update_or_create(
                    module=module,
                    order=lesson_order,
                    defaults={
                        "title": lesson_data["title"],
                        "text_content": lesson_data["text_content"],
                    },
                )
                Assignment.objects.update_or_create(
                    lesson=lesson,
                    type=Assignment.Type.TEXT_ANSWER,
                    defaults={"description": lesson_data["assignment"]},
                )
        self.stdout.write(
            self.style.SUCCESS(f"{'Создан' if created else 'Обновлён'} курс: {course.title}")
        )
